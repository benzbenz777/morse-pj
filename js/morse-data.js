const MORSE = Object.assign({}, EN_MORSE, TH_MORSE);

const EN_REVERSE = (() => {
  const r = {};
  for (const k in EN_MORSE) r[EN_MORSE[k]] = k;
  return r;
})();

const TH_REVERSE = (() => {
  const r = {};
  for (const k in TH_MORSE) if (!r[TH_MORSE[k]]) r[TH_MORSE[k]] = k;
  return r;
})();

function isThaiChar(ch) {
  return ch.charCodeAt(0) >= 0x0E00 && ch.charCodeAt(0) <= 0x0E7F;
}

function textToMorse(text) {
  const tokens = [];
  for (let i = 0; i < text.length; i++) {
    const c = text[i].toUpperCase();
    if (c === ' ' || c === '\n' || c === '\t' || c === '\r') {
      tokens.push({ type: 'space', char: ' ', index: i });
    } else if (MORSE[c]) {
      tokens.push({ type: 'char', char: c, code: MORSE[c], index: i });
    } else {
      tokens.push({ type: 'skip', char: c, index: i });
    }
  }
  return tokens;
}

